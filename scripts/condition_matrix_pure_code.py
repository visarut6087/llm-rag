#!/usr/bin/env python3
"""
Condition Matrix - Pure Code Evaluation for RAG/LLM Answers

Purpose
-------
Compare generated answers against Gold Answers deterministically.

No LLM judge is used.

Input:
    1. answers.json
       Generated by evaluate_llm_nodb_3070ti.py
    2. sarabun-questions100.json
       Gold dataset containing:
           id
           question
           answer

Outputs:
    condition_matrix.json
    condition_matrix.csv
    condition_summary.json

Metrics
-------
1. Answer similarity
   - SequenceMatcher ratio
   - Token F1 against Gold Answer

2. Citation
   - Citation presence
   - Citation validity:
       cited [S#] must exist in retrieved sources
   - Citation precision

3. Grounding heuristic
   - Sentence-level overlap between answer and retrieved Context
   - A sentence is considered "supported" when token overlap with
     the context is >= GROUNDING_THRESHOLD.
   - This is a deterministic heuristic, NOT semantic truth.

4. Hallucination heuristic
   - unsupported sentence ratio
   - Does NOT claim to be a human/LLM semantic hallucination judgment.

5. Overall score
   Default:
       Answer Token F1       50%
       Answer Similarity     20%
       Grounding             20%
       Citation Precision    10%

Important
---------
This is a pure-code Condition Matrix.
It does not use an LLM judge.
Therefore semantic correctness and hallucination are operationalized
using deterministic text-overlap heuristics.
"""

