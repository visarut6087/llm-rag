def choose_results_folder():
    """Open a folder chooser starting at the project's results directory."""
    try:
        import tkinter as tk
        from tkinter import filedialog

        root = tk.Tk()
        root.withdraw()
        root.attributes("-topmost", True)

        initial_dir = RESULTS_ROOT if RESULTS_ROOT.is_dir() else Path.home()

        folder = filedialog.askdirectory(
            title="เลือกโฟลเดอร์ผลลัพธ์ที่ต้องการประเมิน",
            initialdir=str(initial_dir),
            mustexist=True,
        )

        root.destroy()

        if not folder:
            raise SystemExit("ยกเลิกการเลือกโฟลเดอร์")

        return Path(folder).expanduser().resolve()

    except ImportError as exc:
        raise RuntimeError(
            "ไม่สามารถเปิดหน้าต่างเลือกโฟลเดอร์ได้ เนื่องจากไม่มี tkinter"
        ) from exc


def main():
    parser = argparse.ArgumentParser(
        description="Pure-code Condition Matrix - เลือกโฟลเดอร์ answers จาก results ตอนรัน"
    )

    parser.add_argument(
        "--gold",
        default=str(DEFAULT_GOLD),
        help="Path to Gold dataset JSON (default: project/scripts/dataset_for_train/sarabun-questions100.json)",
    )

    parser.add_argument(
        "--output-dir",
        default=None,
        help="Output directory (default: answers folder/condition_matrix)",
    )

    parser.add_argument(
        "--answers",
        default=None,
        help="Path to answers.json. If omitted, a folder is selected interactively from results/.",
    )

    args = parser.parse_args()

    # If --answers is supplied, use it directly. Otherwise select a result
    # subfolder interactively from the configured results directory.
    if args.answers:
        answers_path = Path(args.answers).expanduser().resolve()
        selected_folder = answers_path.parent
    else:
        selected_folder = choose_results_folder()
        answers_path = selected_folder / "answers.json"
    gold_path = Path(args.gold).expanduser().resolve()

    if not answers_path.is_file():
        raise FileNotFoundError(
            f"ไม่พบ answers.json: {answers_path}"
        )

    if not gold_path.is_file():
        raise FileNotFoundError(
            f"ไม่พบ Gold dataset: {gold_path}"
        )

    answers_data = load_json(answers_path)
    rows = load_answers(answers_path)

    gold_data = load_json(gold_path)
    gold = normalize_dataset(gold_data)

    if args.output_dir:
        output_dir = Path(args.output_dir).expanduser().resolve()
    else:
        output_dir = answers_path.parent / "condition_matrix"

    output_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 70)
    print("CONDITION MATRIX - PURE CODE")
    print("=" * 70)
    print(f"Selected: {selected_folder}")
    print(f"Answers : {answers_path}")
    print(f"Gold    : {gold_path}")
    print(f"Rows    : {len(rows)}")
    print(f"Gold    : {len(gold)}")
    print(f"Output  : {output_dir}")
    print("=" * 70)

    results = []

    for index, row in enumerate(rows, 1):
        item_id = str(row.get("id"))

        gold_item = gold.get(item_id)

        result = evaluate_row(
            row=row,
            gold_item=gold_item,
        )

        results.append(result)

        if result["status"] == "SCORED":
            print(
                f"[{index}/{len(rows)}] "
                f"id={item_id} "
                f"score={result['overall_score']} "
                f"{result['condition']}",
                flush=True,
            )
        else:
            print(
                f"[{index}/{len(rows)}] "
                f"id={item_id} "
                f"MISSING_GOLD",
                flush=True,
            )

    summary = build_summary(
        results,
        answers_data,
        gold,
    )

    output_json = output_dir / "condition_matrix.json"
    output_csv = output_dir / "condition_matrix.csv"
    summary_json = output_dir / "condition_summary.json"

    output_data = {
        "method": "pure_code_condition_matrix",
        "source_answers": str(answers_path),
        "source_gold": str(gold_path),
        "weights": WEIGHTS,
        "grounding_threshold": GROUNDING_THRESHOLD,
        "summary": summary,
        "results": results,
    }

    save_json(output_json, output_data)
    save_json(summary_json, summary)

    csv_fields = [
        "id",
        "question",
        "model",
        "status",
        "answer_similarity",
        "answer_f1",
        "citation_present",
        "citations_found",
        "valid_citations",
        "invalid_citations",
        "citation_precision",
        "claim_count",
        "supported_claim_count",
        "unsupported_claim_count",
        "grounding_score",
        "unsupported_claim_ratio",
        "overall_score",
        "condition",
        "latency_ms",
        "prompt_tokens",
        "output_tokens",
        "total_tokens",
    ]

    with output_csv.open(
        "w",
        encoding="utf-8-sig",
        newline="",
    ) as f:
        writer = csv.DictWriter(
            f,
            fieldnames=csv_fields,
        )

        writer.writeheader()

        for row in results:
            writer.writerow(
                {
                    field: (
                        json.dumps(
                            row.get(field),
                            ensure_ascii=False,
                        )
                        if isinstance(
                            row.get(field),
                            (list, dict),
                        )
                        else row.get(field)
                    )
                    for field in csv_fields
                }
            )

    print("\n" + "=" * 70)
    print("CONDITION MATRIX SUMMARY")
    print("=" * 70)

    print(
        f"Scored                  : "
        f"{summary['dataset']['scored']}"
    )

    print(
        f"Missing Gold            : "
        f"{summary['dataset']['missing_gold']}"
    )

    print(
        f"Overall Score           : "
        f"{summary['metrics']['overall_score_0_100']}"
    )

    print(
        f"Answer F1               : "
        f"{summary['metrics']['answer_f1']}"
    )

    print(
        f"Answer Similarity       : "
        f"{summary['metrics']['answer_similarity']}"
    )

    print(
        f"Grounding Score         : "
        f"{summary['metrics']['grounding_score']}"
    )

    print(
        f"Citation Precision      : "
        f"{summary['metrics']['citation_precision']}"
    )

    print(
        f"Unsupported Claim Ratio : "
        f"{summary['metrics']['unsupported_claim_ratio']}"
    )

    print(
        f"Distribution             : "
        f"{summary['condition_distribution']}"
    )

    print("\nFiles:")
    print(f"  {output_json}")
    print(f"  {output_csv}")
    print(f"  {summary_json}")
    print("=" * 70)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
