def average(values):
    values = [v for v in values if isinstance(v, (int, float))]

    if not values:
        return None

    return round(sum(values) / len(values), 4)


def build_summary(results, answers_data, gold):
    scored = [
        r for r in results
        if r.get("status") == "SCORED"
    ]

    missing = [
        r for r in results
        if r.get("status") == "MISSING_GOLD"
    ]

    scores = [r["overall_score"] for r in scored]
    f1s = [r["answer_f1"] for r in scored]
    similarities = [r["answer_similarity"] for r in scored]
    grounding = [r["grounding_score"] for r in scored]
    citation_precision = [
        r["citation_precision"] for r in scored
    ]
    hallucination_ratio = [
        r["unsupported_claim_ratio"] for r in scored
    ]

    condition_counts = {}

    for row in scored:
        label = row["condition"]
        condition_counts[label] = condition_counts.get(label, 0) + 1

    return {
        "model": answers_data.get("model"),

        "dataset": {
            "answers_rows": len(answers_data.get("rows", [])),
            "gold_items": len(gold),
            "scored": len(scored),
            "missing_gold": len(missing),
            "generation_errors": len(
                answers_data.get("errors_detail", [])
            ),
        },

        "metrics": {
            "overall_score_0_100": average(scores),
            "answer_f1": average(f1s),
            "answer_similarity": average(similarities),
            "grounding_score": average(grounding),
            "citation_precision": average(citation_precision),

            # Heuristic only.
            "unsupported_claim_ratio": average(
                hallucination_ratio
            ),
        },

        "condition_distribution": condition_counts,

        "weights": {
            "answer_f1": WEIGHTS["answer_f1"],
            "answer_similarity": WEIGHTS["answer_similarity"],
            "grounding": WEIGHTS["grounding"],
            "citation_precision": WEIGHTS["citation_precision"],
        },

        "grounding_threshold": GROUNDING_THRESHOLD,

        "interpretation": {
            "method": "pure_code",
            "llm_judge": False,
            "hallucination_metric": (
                "unsupported_claim_ratio based on deterministic "
                "answer-context character n-gram overlap; "
                "not a semantic hallucination judgment"
            ),
        },
    }


