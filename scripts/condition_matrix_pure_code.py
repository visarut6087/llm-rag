def normalize_dataset(data):
    """
    Accept:
        [
            {"id": 1, "question": "...", "answer": "..."}
        ]

    or:
        {"items": [...]}
    """
    if isinstance(data, list):
        items = data
    elif isinstance(data, dict):
        items = data.get("items", [])
    else:
        raise ValueError("Gold dataset must be a list or object with 'items'.")

    if not isinstance(items, list):
        raise ValueError("Gold dataset items must be a list.")

    result = {}

    for item in items:
        if not isinstance(item, dict):
            continue

        item_id = item.get("id")

        if item_id is None:
            continue

        result[str(item_id)] = item

    return result


def load_answers(path):
    data = load_json(path)

    if isinstance(data, dict) and isinstance(data.get("rows"), list):
        return data["rows"]

    if isinstance(data, list):
        return data

    raise ValueError(
        "answers.json must contain a 'rows' list or be a list of answer rows."
    )


# ============================================================
# TEXT NORMALIZATION
# ============================================================

def normalize_text(text):
    if not text:
        return ""

    text = str(text)

    # Remove citation tags.
    text = re.sub(r"\[S\d+\]", " ", text, flags=re.IGNORECASE)

    # Normalize Thai/Arabic numerals to Arabic.
    thai_digits = str.maketrans("๐๑๒๓๔๕๖๗๘๙", "0123456789")
    text = text.translate(thai_digits)

    # Normalize whitespace.
    text = re.sub(r"\s+", " ", text)

    # Keep Thai characters, Latin characters and digits.
    # Punctuation is treated as separators.
    text = re.sub(
        r"[^\u0E00-\u0E7Fa-zA-Z0-9]+",
        " ",
        text,
    )

    return text.lower().strip()


def tokenize(text):
    """
    Thai text often has no spaces between words.
    We therefore use a character n-gram representation in addition
    to whitespace tokens.

    This function returns normalized character bigrams/trigrams.
    """
    text = normalize_text(text)

    if not text:
        return []

    # Remove spaces for Thai character-level comparison.
    compact = text.replace(" ", "")

    if len(compact) < 2:
        return [compact] if compact else []

    grams = []

    # Character bigrams.
    for i in range(len(compact) - 1):
        grams.append(compact[i:i + 2])

    # Character trigrams.
    for i in range(len(compact) - 2):
        grams.append(compact[i:i + 3])

    return grams


def word_tokens(text):
    text = normalize_text(text)
    return text.split()


# ============================================================
# SIMILARITY
# ============================================================

def sequence_similarity(a, b):
    a = normalize_text(a)
    b = normalize_text(b)

    if not a and not b:
        return 1.0

    if not a or not b:
        return 0.0

    return SequenceMatcher(None, a, b).ratio()


def f1_score(reference, candidate):
    """
    Character n-gram F1.

    This works better than whitespace-token F1 for Thai because
    Thai answers frequently do not contain spaces between words.
    """
    ref = set(tokenize(reference))
    pred = set(tokenize(candidate))

    if not ref and not pred:
        return 1.0

    if not ref or not pred:
        return 0.0

    overlap = len(ref & pred)

    precision = overlap / len(pred)
    recall = overlap / len(ref)

    if precision + recall == 0:
        return 0.0

    return 2 * precision * recall / (precision + recall)


# ============================================================
# CITATIONS
# ============================================================

def extract_citations(answer):
    if not answer:
        return []

    found = re.findall(
        r"\[S(\d+)\]",
        str(answer),
        flags=re.IGNORECASE,
    )

    result = []
    seen = set()

    for number in found:
        citation = f"S{number}"

        if citation not in seen:
            seen.add(citation)
            result.append(citation)

    return result


def parse_sources(value):
    """
    answers.json stores sources as a JSON string.
    Also supports an already-parsed list.
    """
    if not value:
        return []

    if isinstance(value, list):
        return value

    if isinstance(value, str):
        try:
            parsed = json.loads(value)
            return parsed if isinstance(parsed, list) else []
        except json.JSONDecodeError:
            return []

    return []


def citation_metrics(answer, sources):
    citations = extract_citations(answer)

    known = set()

    for source in sources:
        if isinstance(source, dict):
            cid = source.get("citation_id")

            if cid:
                known.add(str(cid).upper())

    valid = [c for c in citations if c.upper() in known]
    invalid = [c for c in citations if c.upper() not in known]

    if citations:
        precision = len(valid) / len(citations)
    else:
        precision = 0.0

    return {
        "citations_found": citations,
        "valid_citations": valid,
        "invalid_citations": invalid,
        "citation_count": len(citations),
        "valid_citation_count": len(valid),
        "invalid_citation_count": len(invalid),
        "citation_precision": round(precision, 4),
        "citation_present": bool(citations),
    }


# ============================================================
# GROUNDING / HALLUCINATION HEURISTIC
# ============================================================

def split_sentences(text):
    if not text:
        return []

    text = str(text).strip()

    # Thai/English sentence boundaries.
    parts = re.split(
        r"(?<=[.!?。！？])\s+|\n+",
        text,
    )

    return [p.strip() for p in parts if p.strip()]


def overlap_with_context(sentence, context):
    sentence_tokens = set(tokenize(sentence))
    context_tokens = set(tokenize(context))

    if not sentence_tokens:
        return 1.0

    if not context_tokens:
        return 0.0

    overlap = len(sentence_tokens & context_tokens)

    return overlap / len(sentence_tokens)


def grounding_metrics(answer, context):
    sentences = split_sentences(answer)

    # If answer has no sentence punctuation, treat whole answer as one claim.
    if not sentences and answer:
        sentences = [answer]

    if not sentences:
        return {
            "claim_count": 0,
            "supported_claim_count": 0,
            "unsupported_claim_count": 0,
            "grounding_score": 0.0,
            "unsupported_claim_ratio": 0.0,
            "claims": [],
        }

    claims = []
    supported = 0

    for index, sentence in enumerate(sentences, 1):
        overlap = overlap_with_context(sentence, context)

        is_supported = overlap >= GROUNDING_THRESHOLD

        if is_supported:
            supported += 1

        claims.append(
            {
                "claim_no": index,
                "text": sentence,
                "context_overlap": round(overlap, 4),
                "supported": is_supported,
            }
        )

    unsupported = len(sentences) - supported

    grounding_score = supported / len(sentences)
    unsupported_ratio = unsupported / len(sentences)

    return {
        "claim_count": len(sentences),
        "supported_claim_count": supported,
        "unsupported_claim_count": unsupported,
        "grounding_score": round(grounding_score, 4),
        "unsupported_claim_ratio": round(unsupported_ratio, 4),
        "claims": claims,
    }


# ============================================================
# CONDITION MATRIX
# ============================================================

def condition_score(answer_f1, answer_similarity, grounding, citation_precision):
    score = (
        answer_f1 * WEIGHTS["answer_f1"]
        + answer_similarity * WEIGHTS["answer_similarity"]
        + grounding * WEIGHTS["grounding"]
        + citation_precision * WEIGHTS["citation_precision"]
    )

    return round(score * 100, 2)


def condition_label(score):
    if score >= 90:
        return "EXCELLENT"

    if score >= 80:
        return "GOOD"

    if score >= 70:
        return "ACCEPTABLE"

    if score >= 60:
        return "WEAK"

    return "POOR"


# ============================================================
# EVALUATE ONE ROW
# ============================================================

def evaluate_row(row, gold_item):
    answer = row.get("answer", "")
    question = row.get("question", "")

    if gold_item is None:
        return {
            "id": row.get("id"),
            "question": question,
            "model": row.get("model"),
            "status": "MISSING_GOLD",
            "gold_answer": "",
            "answer": answer,
            "answer_similarity": None,
            "answer_f1": None,
            "citation_present": bool(extract_citations(answer)),
            "citation_precision": None,
            "grounding_score": None,
            "unsupported_claim_ratio": None,
            "overall_score": None,
            "condition": "NOT_SCORED",
            "reason": "No Gold Answer found for this ID.",
        }

    gold_answer = gold_item.get("answer", "")

    similarity = sequence_similarity(gold_answer, answer)
    answer_f1 = f1_score(gold_answer, answer)

    sources = parse_sources(row.get("sources"))
    citations = citation_metrics(answer, sources)

    grounding = grounding_metrics(
        answer,
        row.get("context", ""),
    )

    score = condition_score(
        answer_f1=answer_f1,
        answer_similarity=similarity,
        grounding=grounding["grounding_score"],
        citation_precision=citations["citation_precision"],
    )

    return {
        "id": row.get("id"),
        "question": question,
        "model": row.get("model"),

        "status": "SCORED",

        "gold_answer": gold_answer,
        "answer": answer,

        "answer_similarity": round(similarity, 4),
        "answer_f1": round(answer_f1, 4),

        "citation_present": citations["citation_present"],
        "citations_found": citations["citations_found"],
        "valid_citations": citations["valid_citations"],
        "invalid_citations": citations["invalid_citations"],
        "citation_precision": citations["citation_precision"],

        "claim_count": grounding["claim_count"],
        "supported_claim_count": grounding["supported_claim_count"],
        "unsupported_claim_count": grounding["unsupported_claim_count"],
        "grounding_score": grounding["grounding_score"],
        "unsupported_claim_ratio": grounding["unsupported_claim_ratio"],

        "overall_score": score,
        "condition": condition_label(score),

        "latency_ms": row.get("latency_ms"),
        "prompt_tokens": row.get("prompt_tokens"),
        "output_tokens": row.get("output_tokens"),
        "total_tokens": row.get("total_tokens"),
    }


